#!/usr/bin/env node
/**
 * Where the crossings sit, and whether they move with instance size.
 *
 * Article 3's central claim is that a mechanism's measured contribution changes sign across the
 * range of budgets a user might grant. Its second stated threat was that we had not checked whether
 * the crossing itself moves with the instance. This does.
 *
 * The x-axis is MOVES PER CLASS SESSION rather than seconds or moves, because that is the only
 * quantity that is comparable across sizes: a 120-second run buys 5.1M moves at n=3200 and 3.9M at
 * n=12800, and the same absolute move count means very different amounts of progress on instances
 * that differ fourfold in what has to be placed.
 *
 * Only wall-clock points are placed on the axis. The equal-move points measure a different thing —
 * they remove the endogeneity that wall-clock points have — and mixing them is the mistake an
 * earlier version of the paper made.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

// Paths resolve from this file's own location, so the tree can be copied anywhere — the papers ship
// with `_scripts/` beside them and a reader should be able to rebuild every table without editing
// a path. RESULTS is `<script dir>/results`; PAPERS is the article root, one level up.
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { existsSync as pathExists } from 'node:fs';
const HERE = dirname(fileURLToPath(import.meta.url));
const RESULTS = join(HERE, '..', 'records');
// Two layouts must both work: the papers ship with `_scripts/` beside them, and the sandbox keeps
// the harness in its own directory alongside `articles/`. Probe for a paper folder rather than
// assuming either.
const PAPERS = [join(HERE, '..'), join(HERE, '..', 'articles')]
  .find((d) => pathExists(join(d, 'timetable-generation'))) ?? join(HERE, '..');


const OUT = process.argv[2] ?? join(HERE, '..', 'reconstructed');
mkdirSync(OUT, { recursive: true });
const load = (p) => readFileSync(p, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l));
const med = (a) => { const s = [...a].sort((x, y) => x - y); const m = s.length >> 1;
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2; };
const mean = (a) => a.reduce((x, y) => x + y, 0) / a.length;

const POINTS = [
  { n: 3200, secs: 30, file: 'ablation-t30-3200.jsonl' },
  { n: 3200, secs: 120, file: 'ablation-t120-3200.jsonl' },
  { n: 3200, secs: 300, file: 'ablation-t300-3200.jsonl' },
  { n: 6400, secs: 60, file: 'ablation-t60-6400.jsonl' },
  { n: 6400, secs: 180, file: 'ablation-t180-6400.jsonl' },
  { n: 12800, secs: 60, file: 'ablation-time.jsonl' },
  { n: 12800, secs: 120, file: 'ablation-time120.jsonl' },
  { n: 12800, secs: 300, file: 'ablation-time300.jsonl' }
];
const CFG = [['no-chain', 'ejection chain'], ['greedy-accept', 'late acceptance']];

const rows = [];
for (const p of POINTS) {
  const all = load(join(RESULTS, p.file)).filter((r) => r.n === p.n);
  const g = new Map();
  for (const r of all) { if (!g.has(r.config)) g.set(r.config, []); g.get(r.config).push(r); }
  const full = g.get('full'); if (!full) continue;
  const base = med(full.map((r) => r.soft));
  const perSession = mean(full.map((r) => r.moves)) / p.n;
  const cell = {};
  for (const [k] of CFG) {
    const a = g.get(k);
    cell[k] = a ? (100 * (med(a.map((r) => r.soft)) - base)) / base : null;
  }
  rows.push({ ...p, base, perSession, ...cell });
}
rows.sort((a, b) => a.n - b.n || a.secs - b.secs);

/** Bracket the sign change for one configuration at one size. */
function bracket(n, key) {
  const pts = rows.filter((r) => r.n === n && r[key] !== null)
    .sort((a, b) => a.perSession - b.perSession);
  for (let i = 1; i < pts.length; i++) {
    if (pts[i - 1][key] < 0 && pts[i][key] >= 0) {
      return { lo: pts[i - 1].perSession, hi: pts[i].perSession };
    }
  }
  const last = pts[pts.length - 1];
  return last && last[key] < 0 ? { lo: last.perSession, hi: null } : null;
}

let tex = '% generated by crossings.mjs\n\\begin{table}[t]\n\\centering\n';
tex += '\\caption{Wall-clock points only, placed on an axis of \\emph{moves per class session} --- ' +
  'the only budget measure comparable across instance sizes. $\\Delta$ is the change in median soft ' +
  'cost when the mechanism is removed. Each mechanism is monotone within a size, and the two ' +
  'mechanisms behave differently as the instance grows.}\n';
tex += '\\label{tab:crossings}\n\\small\n\\begin{tabular}{@{}rrrrrr@{}}\n\\toprule\n';
tex += '$n$ & budget & moves & per session & $\\Delta$ chain & $\\Delta$ late acc. \\\\\n\\midrule\n';
let lastN = null;
for (const r of rows) {
  if (lastN !== null && r.n !== lastN) tex += '\\addlinespace\n';
  lastN = r.n;
  const f = (v) => (v === null ? '---' : `${v >= 0 ? '+' : ''}${v.toFixed(1)}`);
  tex += `${r.n} & ${r.secs}\\,s & ${(r.perSession * r.n / 1e6).toFixed(1)}M & ` +
    `${Math.round(r.perSession)} & ${f(r['no-chain'])} & ${f(r['greedy-accept'])} \\\\\n`;
}
tex += '\\bottomrule\n\\end{tabular}\n\\end{table}\n';
writeFileSync(`${OUT}/crossings.tex`, tex);

const b = {};
for (const n of [3200, 6400, 12800]) for (const [k] of CFG) b[`${k}${n}`] = bracket(n, k);
// Rendered in TeX, not in Unicode: a thin-spaced number in maths, an en-dash between them, and the
// whole thing usable in text mode — the macros are read inside sentences, and an en-dash typed as
// U+2013 inside $...$ comes out as an accent.
const num = (v) => `$${Math.round(v).toLocaleString('en-US').replace(',', '\\,')}$`;
const fmtB = (x) => (!x ? 'none' : x.hi ? `${num(x.lo)}--${num(x.hi)}` : `above ${num(x.lo)}`);
/**
 * The size-invariance test, stated as an intersection of brackets.
 *
 * Each size gives an interval in which that mechanism's crossing must lie (or a half-line, if it
 * has not crossed by the largest budget measured there). If one budget can be the crossing at every
 * size, those intervals share a point, and the crossing is consistent with being size-invariant. If
 * the intersection is empty, no single per-session budget works at every size and the crossing
 * demonstrably moves. That is a statement three brackets can support, unlike "the crossing is at X",
 * which they cannot.
 */
function intersect(key) {
  let lo = 0, hi = Infinity, seen = 0;
  for (const n of [...new Set(rows.map((r) => r.n))]) {
    const x = bracket(n, key);
    if (!x) continue;
    seen++;
    lo = Math.max(lo, x.lo);
    if (x.hi !== null) hi = Math.min(hi, x.hi);
  }
  return { lo, hi, empty: seen > 0 && lo >= hi, sizes: seen };
}
const INT = Object.fromEntries(CFG.map(([k]) => [k, intersect(k)]));

/**
 * Saturation: two budgets that return the same answer are one budget.
 *
 * This was found by accident. The 300 s batch at n=3200 returned, on every one of fifteen runs
 * across three configurations, EXACTLY the soft cost its 120 s counterpart returned — while
 * performing 2.7x as many moves. The runs are deterministic given the seed, so a longer run does
 * everything the shorter one did and continues; identical answers therefore mean the incumbent
 * never improved again. The extra search found nothing.
 *
 * That matters twice. It means the chain's -6.1% at n=3200 is not a point on a curve heading for
 * zero, it is the final value at that size. And it is a caveat on this paper's own advice to report
 * at least two budgets: they have to be two budgets inside the regime where the search is still
 * improving, and this is the cheap test for it — compare the per-seed values, not the medians.
 */
function saturationPairs() {
  const bySize = new Map();
  for (const p of POINTS) {
    const rows = load(join(RESULTS, p.file)).filter((r) => r.n === p.n);
    if (!rows.length) continue;
    if (!bySize.has(p.n)) bySize.set(p.n, []);
    bySize.get(p.n).push({ secs: p.secs, byKey: new Map(rows.map((r) => [`${r.config}|${r.seed}`, r])) });
  }
  const out = [];
  for (const [n, pts] of bySize) {
    pts.sort((a, b) => a.secs - b.secs);
    for (let i = 1; i < pts.length; i++) {
      const lo = pts[i - 1], hi = pts[i];
      const shared = [...hi.byKey.keys()].filter((k) => lo.byKey.has(k));
      if (!shared.length) continue;
      const same = shared.filter((k) => lo.byKey.get(k).soft === hi.byKey.get(k).soft).length;
      const moveRatio = shared.reduce((a, k) => a + hi.byKey.get(k).moves / lo.byKey.get(k).moves, 0) / shared.length;
      out.push({ n, lo: lo.secs, hi: hi.secs, shared: shared.length, same, moveRatio });
    }
  }
  return out;
}
const SAT = saturationPairs();
console.log('\nbudget pairs, per-seed agreement (all-identical means the larger budget measured nothing):');
for (const x of SAT) {
  console.log(`  n=${String(x.n).padStart(5)}  ${String(x.lo).padStart(3)}s -> ${String(x.hi).padStart(3)}s: ` +
    `${x.same}/${x.shared} runs identical, ${x.moveRatio.toFixed(1)}x the moves` +
    (x.same === x.shared ? '   <-- SATURATED' : ''));
}
const sat = SAT.find((x) => x.same === x.shared && x.shared >= 5);

const crossingFacts =
  '% generated by crossings.mjs\n' +
  `\\newcommand{\\lahcCrossSmall}{${fmtB(b['greedy-accept3200'])}}\n` +
  `\\newcommand{\\lahcCrossLarge}{${fmtB(b['greedy-accept12800'])}}\n` +
  `\\newcommand{\\chainCrossSmall}{${fmtB(b['no-chain3200'])}}\n` +
  `\\newcommand{\\chainCrossLarge}{${fmtB(b['no-chain12800'])}}\n` +
  `\\newcommand{\\lahcCrossMid}{${fmtB(b['greedy-accept6400'])}}\n` +
  `\\newcommand{\\chainCrossMid}{${fmtB(b['no-chain6400'])}}\n` +
  `\\newcommand{\\lahcCrossAll}{${fmtB({ lo: INT['greedy-accept'].lo,
    hi: INT['greedy-accept'].hi === Infinity ? null : INT['greedy-accept'].hi })}}\n` +
  `\\newcommand{\\chainCrossAllEmpty}{${INT['no-chain'].empty ? 'empty' : 'non-empty'}}\n` +
  /**
   * How much further the smallest size has run without crossing, as a multiple.
   *
   * The crossings figure's caption says the chain "has not crossed by nearly six times the effort"
   * at which the largest size has. That is a ratio between two bracket endpoints --- the lower bound
   * of the open bracket at the small size over the upper bound of the closed one at the large size
   * --- and it was arithmetic done in the author's head and typed into a caption, which is the one
   * place in a paper nothing else checks. Emitted here so the caption states a computed quantity.
   */
  (() => {
    const small = b['no-chain3200'], large = b['no-chain12800'];
    if (!small || !large || small.lo == null || large.hi == null) return '';
    return `\\newcommand{\\chainSmallRatio}{${(small.lo / large.hi).toFixed(1)}}\n`;
  })() +
  /**
   * THE ABSTRACT'S HEADLINE, COUNTED RATHER THAN REMEMBERED.
   *
   * "Three of four mechanisms change the sign of their measured contribution" appears in the
   * abstract, in Section 6.6 and in the conclusions, and it was typed in all three. It is a count
   * over the mechanisms this study measured at more than one wall-clock budget --- a set that grew
   * once already, when the 300-second panel was added --- so it is exactly the shape of claim the
   * companion measurement paper reports as an incident: a quantifier over a set the study is still
   * adding to.
   *
   * A mechanism qualifies as tested only if it has two or more wall-clock budgets at some size,
   * because a single budget cannot show a change. It flips if its delta is positive at one of that
   * size's budgets and negative at another, with a half-point dead band so that a cell sitting on
   * zero is not counted as a sign change in whichever direction the noise fell.
   */
  (() => {
    const DEAD = 0.5;
    // Recomputed from the wall-clock files rather than from `rows`, which carries deltas only for
    // the two mechanisms the crossing plot draws. The claim is about every mechanism this study
    // measured at more than one wall-clock budget, so the count has to see all of them --- and the
    // first version of this block did not, silently returning two of four because `rows` has two
    // columns. A count that reads a table built for a different purpose counts that table.
    const deltas = new Map();
    for (const p of POINTS) {
      const all = load(join(RESULTS, p.file)).filter((r) => r.n === p.n);
      const g = new Map();
      for (const r of all) { if (!g.has(r.config)) g.set(r.config, []); g.get(r.config).push(r); }
      const full = g.get('full'); if (!full) continue;
      const base = med(full.map((r) => r.soft));
      for (const [c, a] of g) {
        if (c === 'full') continue;
        const key = `${c}|${p.n}`;
        if (!deltas.has(key)) deltas.set(key, []);
        deltas.get(key).push((100 * (med(a.map((r) => r.soft)) - base)) / base);
      }
    }
    const cfgs = [...new Set([...deltas.keys()].map((k) => k.split('|')[0]))].sort();
    const tested = [], flipped = [];
    for (const c of cfgs) {
      let anyTested = false, anyFlip = false;
      for (const [key, ds] of deltas) {
        if (key.split('|')[0] !== c || ds.length < 2) continue;
        anyTested = true;
        if (ds.some((d) => d > DEAD) && ds.some((d) => d < -DEAD)) anyFlip = true;
      }
      if (anyTested) tested.push(c);
      if (anyFlip) flipped.push(c);
    }
    const WORDS = ['zero', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine', 'ten'];
    console.log(`\nsign changes: ${flipped.length} of ${tested.length} mechanisms tested at 2+ ` +
      `wall-clock budgets flip (${flipped.join(', ')}); tested: ${tested.join(', ')}`);
    return `\\newcommand{\\signFlips}{${WORDS[flipped.length] ?? flipped.length}}\n` +
      `\\newcommand{\\signTested}{${WORDS[tested.length] ?? tested.length}}\n` +
      `\\newcommand{\\signFlipNames}{${flipped.join(', ')}}\n`;
  })() +
  (sat ? `\\newcommand{\\satN}{${Math.round(sat.n).toLocaleString('en-US').replace(',', '\\,')}}\n` +
    `\\newcommand{\\satLo}{${sat.lo}}\n` +
    `\\newcommand{\\satHi}{${sat.hi}}\n` +
    `\\newcommand{\\satRuns}{${sat.shared}}\n` +
    `\\newcommand{\\satMoveRatio}{${sat.moveRatio.toFixed(1)}}\n` : '');
writeFileSync(`${OUT}/crossing-facts.tex`, crossingFacts);
/**
 * The measurement paper's abstract quotes this sign-reversal count as the reason its central rule
 * is "report at least two budgets". It had the number typed. Two papers transcribing one experiment
 * is the failure this collection keeps rediscovering, and the fix that has held is to emit twice.
 */
const SIBLING = null;
if (SIBLING && pathExists(SIBLING)) {
  writeFileSync(`${SIBLING}/crossing-facts.tex`, crossingFacts);
  console.log(`wrote ${SIBLING}/crossing-facts.tex (same macros, for the measurement paper)`);
}

// ── plot data: one file per (mechanism, size) so pgfplots can draw a line each ──
for (const [key, slug] of [['no-chain', 'chain'], ['greedy-accept', 'lahc']]) {
  for (const n of [...new Set(rows.map((r) => r.n))]) {
    const pts = rows.filter((r) => r.n === n && r[key] !== null)
      .sort((a, b) => a.perSession - b.perSession);
    if (pts.length < 1) continue;
    writeFileSync(`${OUT}/cross-${slug}-${n}.dat`,
      'perSession delta\n' + pts.map((r) => `${r.perSession.toFixed(1)} ${r[key].toFixed(2)}`).join('\n') + '\n');
  }
}

console.log('n     secs  perSession   chain    lateAcc');
for (const r of rows) {
  console.log(String(r.n).padStart(5), String(r.secs).padStart(5),
    String(Math.round(r.perSession)).padStart(11),
    (r['no-chain'] === null ? '—' : r['no-chain'].toFixed(1)).padStart(8),
    (r['greedy-accept'] === null ? '—' : r['greedy-accept'].toFixed(1)).padStart(10));
}
console.log('\ncrossings, in moves per class session:');
for (const [k, lbl] of CFG) {
  console.log(' ', lbl.padEnd(16),
    'n=3200:', fmtB(b[`${k}3200`]).padStart(10),
    ' n=6400:', fmtB(b[`${k}6400`]).padStart(10),
    ' n=12800:', fmtB(b[`${k}12800`]).padStart(10));
}
console.log('\nintersection of the per-size brackets (a single size-invariant crossing must lie here):');
for (const [k, lbl] of CFG) {
  const x = INT[k];
  console.log(' ', lbl.padEnd(16), x.empty ? 'EMPTY — the crossing moves with n'
    : `${Math.round(x.lo)}–${x.hi === Infinity ? 'inf' : Math.round(x.hi)} over ${x.sizes} sizes`);
}
console.log(`wrote ${OUT}/crossings.tex, crossing-facts.tex`);
