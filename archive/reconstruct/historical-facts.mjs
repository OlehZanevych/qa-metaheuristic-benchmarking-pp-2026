#!/usr/bin/env node
/**
 * Historical figures quoted in the article that the original scripts did not emit as macros,
 * recomputed from the archived records (archive/records). Writes reconstructed/historical-facts.tex.
 *   Incident 1: throughput of the complete solver (v20-shipped), n = 3200, seed 1, 30 s, on
 *               2026-08-11 and 2026-08-12 (results.jsonl, moves / solver elapsed time).
 *   Incident 9: infeasible runs of the browser-portfolio batch at n = 12 800 (portfolio.jsonl).
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const HERE = dirname(fileURLToPath(import.meta.url));
const REC = join(HERE, '..', 'records');
const OUT = process.argv[2] ?? join(HERE, '..', 'reconstructed');
const load = (f) => readFileSync(join(REC, f), 'utf8').split('\n').filter(Boolean).map(JSON.parse);

const canary = load('results.jsonl').filter((r) => r.variant === 'v20-shipped.ts' && r.n === 3200 && r.seed === 1 && r.timeBudgetMs === 30000)
  .map((r) => ({ ts: r.ts, mps: Math.round(r.iterations / (r.solverElapsedMs / 1000)) }));
if (canary.length !== 2) throw new Error(`expected two archived 30 s runs of the complete solver at n=3200 seed 1, found ${canary.length}`);
const [before, after] = canary.sort((a, b) => a.ts.localeCompare(b.ts));
const pf = load('portfolio.jsonl').filter((r) => r.n === 12800);
const pfInf = pf.filter((r) => !r.feasible || r.hard > 0).length;
const pfFirst8 = pf.filter((r) => r.worker < 8), pfFirst8Inf = pfFirst8.filter((r) => !r.feasible || r.hard > 0).length;
const g = (x) => String(x).replace(/\B(?=(\d{3})+(?!\d))/g, '\\,');
mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, 'historical-facts.tex'), ['% generated by archive/reconstruct/historical-facts.mjs -- do not edit',
  `\\newcommand{\\histMpsHigh}{${g(before.mps)}}`, `\\newcommand{\\histMpsLow}{${g(after.mps)}}`,
  `\\newcommand{\\histMpsHighDate}{${before.ts.slice(0, 10)}}`, `\\newcommand{\\histMpsLowDate}{${after.ts.slice(0, 10)}}`,
  `\\newcommand{\\histDriftPct}{${(100 * (before.mps - after.mps) / before.mps).toFixed(0)}}`,
  `\\newcommand{\\histPfRuns}{${pf.length}}`, `\\newcommand{\\histPfInf}{${pfInf}}`,
  `\\newcommand{\\histPfFirstEight}{${pfFirst8.length}}`, `\\newcommand{\\histPfFirstEightInf}{${pfFirst8Inf}}`].join('\n') + '\n');
console.log({ before, after, pf: pf.length, pfInf, pfFirst8: pfFirst8.length, pfFirst8Inf });
